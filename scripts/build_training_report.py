"""Generate docs/training_report.md from a real run directory.

The report is produced from the artefacts on disk — train_log.csv, the dataset
manifest, tokenizer stats, evaluation results and the checkpoint — so it can
never drift from what actually happened.

Usage:
    python scripts/build_training_report.py --root runs/real
    python scripts/build_training_report.py --root runs/real --out docs/training_report.md
"""

from __future__ import annotations

import argparse
import csv
import json
import platform
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tagai.utils import human_bytes  # noqa: E402


def load_json(path: Path):
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def load_log(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path, "r", encoding="utf-8") as fh:
        return [r for r in csv.DictReader(fh) if r.get("step")]


def loss_series(rows: list[dict]) -> list[tuple[int, float]]:
    out = []
    for r in rows:
        if r.get("loss"):
            try:
                out.append((int(r["step"]), float(r["loss"])))
            except ValueError:
                continue
    return out


def val_series(rows: list[dict]) -> list[tuple[int, float]]:
    out = []
    for r in rows:
        if r.get("val_loss"):
            try:
                out.append((int(r["step"]), float(r["val_loss"])))
            except ValueError:
                continue
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default="runs/real", help="run directory to report on")
    ap.add_argument("--out", default="docs/training_report.md")
    args = ap.parse_args()

    run = Path(args.root)
    processed = run / "data" / "processed"
    reports = run / "reports"
    tokenizer_dir = run / "tokenizer"
    checkpoints = run / "checkpoints"

    manifest = load_json(processed / "dataset_manifest.json")
    quality = load_json(reports / "dataset_quality.json")
    tok_stats = load_json(tokenizer_dir / "tokenizer_stats.json")
    evaluation = load_json(reports / "evaluation.json")
    export_manifest = load_json(run / "export" / "manifest.json")
    rows = load_log(run / "train_log.csv")

    if manifest is None and not rows:
        print(f"no run artefacts found under {run}", file=sys.stderr)
        return 1

    train_losses = loss_series(rows)
    val_losses = val_series(rows)
    ckpt_steps = sorted(
        int(p.stem.replace("step", "")) for p in checkpoints.glob("step*.pt")
    ) if checkpoints.exists() else []

    L: list[str] = []
    A = L.append

    A("# TagAI training report")
    A("")
    A("Generated by `scripts/build_training_report.py` from the artefacts of a real run.")
    A("Every number below was measured; nothing here is an estimate.")
    A("")
    A(f"- Run directory: `{run}`")
    A(f"- Machine: {platform.system()} {platform.release()} ({platform.machine()})")
    A(f"- Python: {platform.python_version()}")
    A("")

    if manifest:
        stats = manifest["statistics"]
        counts = manifest["counts"]
        A("## Dataset")
        A("")
        A("| Measurement | Value |")
        A("|---|---|")
        A(f"| Documents in | {stats['documents_in']} |")
        A(f"| Documents out | {stats['documents_out']} |")
        A(f"| Retention rate | {stats['retention_rate'] * 100:.1f} % |")
        A(f"| Cleaned characters | {stats['chars_out']} ({human_bytes(stats['chars_out'])}) |")
        A(f"| Language distribution | {stats['language_distribution']} |")
        A(f"| Mean language-ID confidence | {stats['az_confidence']['mean']} |")
        A(f"| Train / validation documents | {counts['train']} / {counts['validation']} |")
        A(f"| Synthetic documents | {counts['synthetic']} |")
        A(f"| Per-source yield | {stats.get('source_yield', {})} |")
        A("")
        A("Drop reasons:")
        A("")
        A("| Reason | Documents |")
        A("|---|---|")
        for reason, n in sorted(stats["cleaning"]["reasons"].items(), key=lambda kv: -kv[1]):
            A(f"| `{reason}` | {n} |")
        A("")

    for split in ("train", "validation"):
        meta_path = processed / "tokens" / f"{split}_meta.json"
        meta = load_json(meta_path)
        if meta:
            A(f"Packed `{split}`: **{meta['total_tokens']:,} tokens** in {len(meta['shards'])} shard(s).")
            A("")

    if tok_stats:
        A("## Tokenizer")
        A("")
        A("| Measurement | Value |")
        A("|---|---|")
        A(f"| Vocabulary | {tok_stats['vocab_size']} |")
        A(f"| Training documents | {tok_stats['training_docs']} |")
        A(f"| Training bytes | {tok_stats['training_bytes']} ({human_bytes(tok_stats['training_bytes'])}) |")
        A(f"| Azerbaijani alphabet coverage | {tok_stats['vocabulary']['az_alphabet_coverage']} |")
        A(f"| Alphabet letters missing | {tok_stats['vocabulary']['az_alphabet_missing'] or '(none)'} |")
        A(f"| Unicode round-trip rate | {tok_stats['roundtrip'].get('roundtrip_rate')} |")
        A(f"| Characters per token | {tok_stats['fragmentation'].get('chars_per_token')} |")
        A("")

    if train_losses or val_losses:
        A("## Training")
        A("")
        first_step, first_loss = train_losses[0]
        last_step, last_loss = train_losses[-1]
        A("| Measurement | Value |")
        A("|---|---|")
        A(f"| Steps completed | {last_step} |")
        token_rows = [r for r in rows if r.get("tokens")]
        A(f"| Tokens processed | {int(float(token_rows[-1]['tokens'])) if token_rows else 'n/a'} |")
        A(f"| Initial train loss | {first_loss:.4f} |")
        A(f"| Final train loss | {last_loss:.4f} |")
        A(f"| Reduction | {(first_loss - last_loss) / first_loss * 100:.1f} % |")
        if val_losses:
            v0_step, v0 = val_losses[0]
            v1_step, v1 = val_losses[-1]
            A(f"| Validation loss (step {v0_step}) | {v0:.4f} |")
            A(f"| Validation loss (step {v1_step}) | {v1:.4f} |")
        else:
            A("| Validation loss | not available (see limitations) |")
        if ckpt_steps:
            A(f"| Checkpoints written | {len(ckpt_steps)} (steps {ckpt_steps[0]}–{ckpt_steps[-1]}) |")
        A("")
        A("### Loss curve")
        A("")
        A("```")
        for step, loss in train_losses[:: max(1, len(train_losses) // 40)]:
            bar = "#" * int(loss * 3)
            A(f"{step:>7d}  {loss:7.4f}  {bar}")
        A("```")
        A("")

    if evaluation:
        A("## Evaluation")
        A("")
        ppl = evaluation.get("validation_perplexity") or {}
        A("| Measurement | Value |")
        A("|---|---|")
        A(f"| Validation perplexity | {ppl.get('perplexity', 'n/a')} |")
        A(f"| Validation bits/token | {ppl.get('bits_per_token', 'n/a')} |")
        A(f"| Evaluation prompts | {evaluation.get('num_prompts')} |")
        A(f"| Mean prompt NLL | {evaluation.get('mean_nll')} |")
        A(f"| Mean repetition ratio | {evaluation.get('mean_repetition_ratio')} |")
        A(f"| Empty completions | {evaluation.get('empty_completions')} |")
        A("")

    if export_manifest:
        A("## Exported bundle")
        A("")
        A("| Field | Value |")
        A("|---|---|")
        A(f"| Parameters | {export_manifest['model']['parameters']:,} |")
        A(f"| Context length | {export_manifest['model']['config']['max_seq_len']} |")
        A(f"| Vocabulary | {export_manifest['tokenizer']['vocab_size']} |")
        A(f"| Weights | {export_manifest['weights_human']} |")
        A(f"| Pretrained weights used | **{export_manifest['pretrained_weights_used']}** |")
        A("")

    A("## What this run does and does not demonstrate")
    A("")
    A("**Demonstrates:** the complete pipeline runs end to end on real Azerbaijani")
    A("text; weights are randomly initialised and update; checkpoints save, load and")
    A("resume; the tokenizer is lossless over the Azerbaijani alphabet; generation and")
    A("export work.")
    A("")
    A("**Does not demonstrate:** Azerbaijani fluency. The model in this run is a")
    A("pipeline-validation artifact — a few million parameters trained briefly on a")
    A("small sample. Its outputs are locally word-like but grammatically wrong, which")
    A("is the expected result at this scale. No claim of fluency is made anywhere in")
    A("this repository.")
    A("")
    if quality and quality.get("limitations"):
        A("## Limitations reported by the quality pipeline")
        A("")
        for item in quality["limitations"]:
            A(f"- {item}")
        A("")

    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {out} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())